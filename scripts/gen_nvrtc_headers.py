#!/usr/bin/env python3
"""Embed the shipped NVRTC harnesses and their quoted project includes.

Run at build time, rewriting only on content changes. The compiler receives the
original headers under their original include names; no runtime checkout is needed.
Standard-library shims are supplied separately by nvrtc_jit.cpp.
"""
from __future__ import annotations

import argparse
import hashlib
import re
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
ROOTS = (REPO / "modules", REPO / "include")
HARNESS_HEADERS = (
    "fused/fused_block/warp_fusion.cuh",
    "fused/fused_block/warp_ti_fusion.cuh",
    "fused/chunk_fusion/chunk_fusion.cuh",
)
INCLUDE_RE = re.compile(r'^\s*#\s*include\s*"([^"\n]+)"', re.MULTILINE)


def collect_headers() -> dict[str, str]:
    headers: dict[str, str] = {}

    def visit(name: str, parent: Path | None = None) -> None:
        if name in headers:
            return
        candidates = [root / name for root in ROOTS]
        if parent is not None:
            candidates.insert(0, parent / name)
        path = next((p for p in candidates if p.is_file()), None)
        if path is None:
            raise RuntimeError(f"Unresolved NVRTC project include: {name}")
        source = path.read_text(encoding="utf-8")
        headers[name] = source
        for included in INCLUDE_RE.findall(source):
            visit(included, path.parent)

    for harness in HARNESS_HEADERS:
        visit(harness)
    return headers


def generate() -> str:
    parts = [
        "// Generated by scripts/gen_nvrtc_headers.py; do not edit.\n",
        "#pragma once\n",
        "namespace fz { namespace fused { namespace detail {\n",
        "struct NvrtcHeader { const char* name; const char* source; };\n",
        "static const NvrtcHeader kNvrtcHeaders[] = {\n",
    ]
    for name, source in sorted(collect_headers().items()):
        delimiter = "FZ" + hashlib.sha256(source.encode()).hexdigest()[:12]
        if f'){delimiter}"' in source:
            raise RuntimeError(f"Raw-string delimiter collision in {name}")
        parts.append(f'{{"{name}", R"{delimiter}({source}){delimiter}"}},\n')
    parts.append("};\n}}} // namespace fz::fused::detail\n")
    return "".join(parts)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    content = generate()
    args.out.parent.mkdir(parents=True, exist_ok=True)
    if not args.out.exists() or args.out.read_text(encoding="utf-8") != content:
        args.out.write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
